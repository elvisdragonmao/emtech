import { writeFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { format, resolveConfig } from "prettier";

const UNICODE_EMOJI_VERSION = "17.0";
const SOURCE_URL = `https://www.unicode.org/Public/${UNICODE_EMOJI_VERSION}.0/emoji/emoji-test.txt`;
const OUTPUT_URL = new URL("../apps/blog/src/data/comment-emojis.generated.ts", import.meta.url);

const CATEGORY_METADATA = new Map([
	["Smileys & Emotion", { id: "smileys-emotion", label: "表情", icon: "😀" }],
	["People & Body", { id: "people-body", label: "人物", icon: "👋" }],
	["Animals & Nature", { id: "animals-nature", label: "動物與自然", icon: "🐻" }],
	["Food & Drink", { id: "food-drink", label: "飲食", icon: "🍜" }],
	["Travel & Places", { id: "travel-places", label: "旅遊與地點", icon: "🚗" }],
	["Activities", { id: "activities", label: "活動", icon: "⚽" }],
	["Objects", { id: "objects", label: "物件", icon: "💡" }],
	["Symbols", { id: "symbols", label: "符號", icon: "❤️" }],
	["Flags", { id: "flags", label: "旗幟", icon: "🏳️" }]
]);

const response = await fetch(SOURCE_URL);
if (!response.ok) {
	throw new Error(`Unable to download Unicode emoji data: ${response.status} ${response.statusText}`);
}

const source = await response.text();
if (!source.includes(`# Version: ${UNICODE_EMOJI_VERSION}`)) {
	throw new Error(`Unexpected Unicode emoji data version from ${SOURCE_URL}`);
}

const groups = [];
let currentGroup = null;

for (const line of source.split(/\r?\n/)) {
	const groupName = line.match(/^# group: (.+)$/)?.[1];
	if (groupName) {
		const metadata = CATEGORY_METADATA.get(groupName);
		currentGroup = metadata ? { ...metadata, emojis: [] } : null;
		if (currentGroup) groups.push(currentGroup);
		continue;
	}

	if (!currentGroup || !line.includes("; fully-qualified")) continue;
	const codePoints = line
		.split(";", 1)[0]
		?.trim()
		.split(/\s+/)
		.map(value => Number.parseInt(value, 16));
	if (!codePoints?.length || codePoints.some(value => !Number.isFinite(value))) continue;
	currentGroup.emojis.push(String.fromCodePoint(...codePoints));
}

if (groups.length !== CATEGORY_METADATA.size || groups.some(group => group.emojis.length === 0)) {
	throw new Error(`Parsed ${groups.length} populated categories; expected ${CATEGORY_METADATA.size}`);
}

const totalEmoji = groups.reduce((total, group) => total + group.emojis.length, 0);
const output = `// This file is generated by scripts/generate-comment-emoji-data.mjs.
// Source: ${SOURCE_URL}
// Unicode data terms: https://www.unicode.org/terms_of_use.html
// Do not edit this file directly.

export const COMMENT_EMOJI_DATA_VERSION = "${UNICODE_EMOJI_VERSION}";

export const COMMENT_EMOJI_CATEGORIES: readonly {
\tid: string;
\tlabel: string;
\ticon: string;
\temojis: readonly string[];
}[] = ${JSON.stringify(groups, null, "\t")};
`;

const outputPath = fileURLToPath(OUTPUT_URL);
const formattedOutput = await format(output, { ...(await resolveConfig(outputPath)), filepath: outputPath });
await writeFile(outputPath, formattedOutput, "utf8");
console.log(`Generated ${totalEmoji} emoji across ${groups.length} categories in ${outputPath}`);
